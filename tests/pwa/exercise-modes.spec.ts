import { expect, test } from '@playwright/test'

test('all three catalogues switch the picker and persist without losing exercises or sets', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.getByText('Aplikacja gotowa do pracy offline', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Zamknij', exact: true }).click()
  const gymChip = page.getByRole('button', { name: 'Siłownia', exact: true })
  const womenChip = page.getByRole('button', { name: 'Siłownia woman', exact: true })
  const calisthenicsChip = page.getByRole('button', { name: 'Kalistenika', exact: true })
  await expect(calisthenicsChip).toHaveAttribute('aria-pressed', 'true')
  await womenChip.click()
  await expect(womenChip).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Rozpocznij trening', exact: true }).click()
  await page.getByRole('button', { name: 'Dodaj lub wybierz ćwiczenie' }).click()
  const picker = page.getByRole('dialog')
  const benchPress = 'Wyciskanie sztangi na ławce płaskiej'
  const benchOption = picker.getByRole('button', { name: new RegExp(benchPress) })
  await expect(picker.getByRole('button', { name: 'Siłownia woman', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(picker.getByRole('button', { name: /Hip thrust/ })).toBeVisible()
  await expect(picker.getByRole('button', { name: /Podciąganie nachwytem/ })).toHaveCount(0)
  await expect(benchOption).toHaveCount(0)
  await picker.getByRole('button', { name: /Hip thrust/ }).click()
  await expect(page.getByRole('checkbox', { name: 'Wariant z obciążeniem' })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Ciężar (kg)', exact: true }).fill('40')
  await page.getByRole('button', { name: '+ Dodaj serię', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edytuj serię 1: Hip thrust' })).toBeVisible()

  await page.getByRole('button', { name: 'Dodaj lub wybierz ćwiczenie' }).click()
  await picker.getByRole('button', { name: 'Siłownia', exact: true }).click()
  await expect(picker.getByRole('button', { name: 'Siłownia', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(picker.getByRole('button', { name: /Ściąganie drążka wyciągu górnego/ })).toBeVisible()
  await expect(picker.getByRole('button', { name: /Wyciskanie na klatkę na maszynie/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('gym-picker-mobile.png') })
  await picker.getByRole('searchbox', { name: 'Szukaj ćwiczenia' }).fill('sztangi plaskiej')
  await benchOption.click()
  await expect(page.getByRole('textbox', { name: 'Ciężar (kg)', exact: true })).toHaveValue('0')
  await page.getByRole('textbox', { name: 'Ciężar (kg)', exact: true }).fill('60')
  await page.getByRole('button', { name: '+ Dodaj serię', exact: true }).click()
  await expect(page.getByRole('button', { name: `Edytuj serię 1: ${benchPress}` })).toBeVisible()

  await page.reload()
  await expect(gymChip).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Kontynuuj trening', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edytuj serię 1: Hip thrust' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Ciężar (kg)', exact: true })).toHaveValue('60')
  await page.getByRole('button', { name: 'Edytuj serię 1: Hip thrust' }).click()
  await expect(page.getByRole('dialog').getByRole('checkbox', { name: 'Wariant z obciążeniem' })).toHaveCount(0)
  await page.getByRole('dialog').getByRole('textbox', { name: 'Ciężar (kg)', exact: true }).fill('42,5')
  await page.getByRole('button', { name: 'Zapisz serię', exact: true }).click()
  await expect(page.locator('article').filter({ has: page.getByRole('heading', { name: 'Hip thrust', exact: true }) })).toContainText('+42,5 kg')
  await expect(page.getByRole('textbox', { name: 'Ciężar (kg)', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dodaj lub wybierz ćwiczenie' }).click()
  await page.getByRole('searchbox', { name: 'Szukaj ćwiczenia' }).fill('bulgarskie')
  await picker.getByRole('button', { name: /Przysiady bułgarskie/ }).click()
  await expect(page.getByRole('checkbox', { name: 'Wariant z obciążeniem' })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Ciężar (kg)', exact: true })).toHaveValue('0')
  await page.getByRole('button', { name: 'Dodaj lub wybierz ćwiczenie' }).click()
  await picker.getByRole('button', { name: 'Kalistenika', exact: true }).click()
  await expect(picker.getByRole('button', { name: 'Kalistenika', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(picker.getByRole('button', { name: /Hip thrust/ })).toHaveCount(0)
  await expect(benchOption).toHaveCount(0)
  await expect(picker.getByRole('button', { name: /Podciąganie nachwytem/ })).toBeVisible()
  await picker.getByRole('button', { name: /Podciąganie nachwytem/ }).click()
  await expect(page.getByRole('checkbox', { name: 'Wariant z obciążeniem' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Dodatkowy ciężar (kg)', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Hip thrust', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Przysiady bułgarskie', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edytuj serię 1: Hip thrust' })).toBeVisible()
  await expect(page.getByRole('button', { name: `Edytuj serię 1: ${benchPress}` })).toBeVisible()
  await page.reload()
  await expect(calisthenicsChip).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Kontynuuj trening', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edytuj serię 1: Hip thrust' })).toBeVisible()
})
